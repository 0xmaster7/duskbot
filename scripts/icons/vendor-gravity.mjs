// Writes src/icons/gravity.ts: the path data of every Gravity UI icon (MIT) that src/icons/index.ts names as G.Name,
// read from the @gravity-ui/icons dev dependency. Run after naming a new one: node scripts/icons/vendor-gravity.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const svgs = `${root}node_modules/@gravity-ui/icons/svgs/`;
const pascal = (file) => file.replace(/\.svg$/, "").split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join("");
const files = new Map(readdirSync(svgs).map((file) => [pascal(file), file]));
const { version } = JSON.parse(readFileSync(`${root}node_modules/@gravity-ui/icons/package.json`, "utf8"));

const names = [...new Set([...readFileSync(`${root}src/icons/index.ts`, "utf8").matchAll(/\bG\.(\w+)/g)].map((m) => m[1]))].sort();
const out = [];
for (const name of names) {
  const file = files.get(name);
  if (!file) throw new Error(`gravity has no ${name}`);
  const svg = readFileSync(svgs + file, "utf8").replace(/<defs>.*?<\/defs>/gs, "");
  const box = Number(/viewBox="0 0 (\d+) \1"/.exec(svg)?.[1]);
  if (!box) throw new Error(`${name} is not square`);
  const groupFill = /<g fill="currentColor">/.test(svg);
  const paths = [...svg.matchAll(/<path ([^>]*)\/>/g)].map(([, attrs]) => {
    const fill = /fill="([^"]+)"/.exec(attrs)?.[1] ?? (groupFill ? "currentColor" : undefined);
    // the app's icons are one colour, the caller's: a painted accent (bell-dot's red dot) takes it too
    if (!fill || fill === "none") throw new Error(`${name} has an unfilled path`);
    const d = /\bd="([^"]+)"/.exec(attrs)[1];
    return `[${JSON.stringify(d)}, ${/fill-rule="evenodd"/.test(attrs) ? 1 : 0}]`;
  });
  if (!paths.length) throw new Error(`${name} has no path`);
  out.push(`export const ${name}: Art = { paths: [${paths.join(", ")}]${box === 16 ? "" : `, box: ${box}`} };`);
}
writeFileSync(
  `${root}src/icons/gravity.ts`,
  `// Gravity UI icons ${version}, https://github.com/gravity-ui/icons, MIT License, Copyright (c) 2022 YANDEX LLC.\n// Generated by scripts/icons/vendor-gravity.mjs.\nimport type { Art } from "./glyph";\n\n${out.join("\n")}\n`,
);
console.log(`${names.length} icons`);

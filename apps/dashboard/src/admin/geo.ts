export function countryName(code: string | null | undefined): string {
  if (!code) return "unknown";
  return Object.hasOwn(COUNTRIES, code.toUpperCase()) ? COUNTRIES[code.toUpperCase()].name : code.toLowerCase();
}

export function centroid(code: string | null | undefined): [number, number] | null {
  if (!code || !Object.hasOwn(COUNTRIES, code.toUpperCase())) return null;
  const country = COUNTRIES[code.toUpperCase()];
  return [country.lon, country.lat];
}
